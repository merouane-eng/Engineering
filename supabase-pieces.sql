create table if not exists public.pieces_rechange (
  uuid text primary key,
  reference text unique,
  nom text not null,
  description text,
  fournisseur text,
  actif integer not null default 1,
  date_creation timestamptz not null,
  date_modification timestamptz
);

create table if not exists public.pieces_machines (
  id bigint generated by default as identity primary key,
  piece_uuid text not null references public.pieces_rechange(uuid) on delete cascade,
  machine text not null,
  commentaire text,
  date_creation timestamptz not null,
  unique (piece_uuid, machine)
);

create table if not exists public.pieces_utilisees (
  uuid text primary key,
  panne_uuid text references public.pannes(uuid) on delete cascade,
  wo text,
  machine text not null,
  unite text,
  piece_uuid text references public.pieces_rechange(uuid) on delete set null,
  nom_piece text not null,
  reference_piece text,
  description_piece text,
  quantite integer not null default 1,
  date_utilisation timestamptz not null,
  technicien text,
  commentaire text,
  date_creation timestamptz not null
);

alter table public.pannes add column if not exists pieces_consommees text;
notify pgrst, 'reload schema';

create index if not exists idx_cloud_pieces_machine on public.pieces_machines(machine);
create index if not exists idx_cloud_pieces_utilisees_panne on public.pieces_utilisees(panne_uuid);
create index if not exists idx_cloud_pieces_utilisees_machine on public.pieces_utilisees(machine);
